"""Verify that every Step 2 data copy still matches its Phase 1 source.

The checker deliberately has one narrow responsibility: copy integrity. It
does not repeat Phase 1 data-quality checks and it does not exercise the
tabular adapter API. For every file declared in the Step 2 manifest, it checks
existence, byte size, preserved modification time, and byte-for-byte content.

No hashes are calculated or stored. The standard-library file comparison reads
the files directly when checking their contents.
"""

from __future__ import annotations

import argparse
from datetime import datetime, UTC
import filecmp
import json
from pathlib import Path
import sys
from typing import Any


STEP_DIR = Path(__file__).resolve().parent
REPOSITORY_ROOT = STEP_DIR.parents[2]
DEFAULT_MANIFEST_PATH = STEP_DIR / "artifacts" / "tabular_dataset_manifest.json"
DEFAULT_REPORT_PATH = STEP_DIR / "artifacts" / "copy_verification.json"


class CopyVerificationError(ValueError):
    """Represent a readable manifest or copy-integrity failure."""


def _load_manifest(path: Path) -> dict[str, Any]:
    """Read the generated manifest and require its top-level file mapping.

    The manifest is generated by the Step 2 builder, but the checker may also
    be run independently. A small structural check therefore produces a clear
    message when the wrong JSON file is supplied.
    """

    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise CopyVerificationError(
            f"Cannot read tabular dataset manifest {path}: {error}"
        ) from error

    files = payload.get("files") if isinstance(payload, dict) else None
    if not isinstance(files, dict) or not files:
        raise CopyVerificationError(
            "The tabular dataset manifest must contain a non-empty files object"
        )
    return payload


def _safe_source_path(relative_path: str) -> Path:
    """Resolve a repository-relative source without allowing path escape."""

    supplied = Path(relative_path)
    if supplied.is_absolute():
        raise CopyVerificationError(
            f"Source path must be repository-relative: {relative_path}"
        )

    resolved = (REPOSITORY_ROOT / supplied).resolve()
    try:
        resolved.relative_to(REPOSITORY_ROOT.resolve())
    except ValueError as error:
        raise CopyVerificationError(
            f"Source path escapes the repository: {relative_path}"
        ) from error
    return resolved


def _safe_copied_path(manifest_path: Path, relative_path: str) -> Path:
    """Resolve a copy relative to its manifest without allowing path escape."""

    supplied = Path(relative_path)
    if supplied.is_absolute():
        raise CopyVerificationError(
            f"Copied path must be manifest-relative: {relative_path}"
        )

    artifact_dir = manifest_path.resolve().parent
    resolved = (artifact_dir / supplied).resolve()
    try:
        resolved.relative_to(artifact_dir)
    except ValueError as error:
        raise CopyVerificationError(
            f"Copied path escapes the artifact directory: {relative_path}"
        ) from error
    return resolved


def _readable_utc_timestamp(modified_time: float) -> str:
    """Convert a filesystem timestamp to a human-readable UTC value."""

    return datetime.fromtimestamp(modified_time, tz=UTC).isoformat()


def _inspect_pair(
    *,
    name: str,
    source_label: str,
    copied_label: str,
    source_path: Path,
    copied_path: Path,
) -> dict[str, Any]:
    """Compare one source/copy pair and return JSON-compatible observations.

    Every individual check is reported even when another check fails. This
    makes the saved report useful for diagnosing whether a file is missing,
    stale, truncated, or different despite matching metadata.
    """

    source_exists = source_path.is_file()
    copied_exists = copied_path.is_file()

    source_stat = source_path.stat() if source_exists else None
    copied_stat = copied_path.stat() if copied_exists else None

    size_matches = bool(
        source_stat
        and copied_stat
        and source_stat.st_size == copied_stat.st_size
    )
    timestamp_matches = bool(
        source_stat
        and copied_stat
        and source_stat.st_mtime_ns == copied_stat.st_mtime_ns
    )

    # Deep comparison is intentional. The default shallow comparison may trust
    # matching filesystem metadata without reading and comparing file contents.
    content_matches = bool(
        source_exists
        and copied_exists
        and filecmp.cmp(source_path, copied_path, shallow=False)
    )

    checks = {
        "source_exists": source_exists,
        "copy_exists": copied_exists,
        "size_matches": size_matches,
        "timestamp_matches": timestamp_matches,
        "content_matches": content_matches,
    }
    passed = all(checks.values())

    return {
        "name": name,
        "source_path": source_label,
        "copied_path": copied_label,
        "source_size_bytes": source_stat.st_size if source_stat else None,
        "copied_size_bytes": copied_stat.st_size if copied_stat else None,
        "source_modified_time_ns": (
            source_stat.st_mtime_ns if source_stat else None
        ),
        "copied_modified_time_ns": (
            copied_stat.st_mtime_ns if copied_stat else None
        ),
        "source_modified_time_utc": (
            _readable_utc_timestamp(source_stat.st_mtime)
            if source_stat
            else None
        ),
        "copied_modified_time_utc": (
            _readable_utc_timestamp(copied_stat.st_mtime)
            if copied_stat
            else None
        ),
        "checks": checks,
        "passed": passed,
    }


def _write_report(report: dict[str, Any], path: Path) -> None:
    """Write a stable and readable verification report."""

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(report, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )


def verify_copied_files(
    manifest_path: Path = DEFAULT_MANIFEST_PATH,
    report_path: Path = DEFAULT_REPORT_PATH,
) -> dict[str, Any]:
    """Check all declared copies, save the report, and fail on any mismatch.

    The report is written for both successful and unsuccessful comparisons.
    Callers therefore retain a concrete explanation even when this function
    raises an exception and stops the pipeline.
    """

    manifest = _load_manifest(manifest_path)
    observations: dict[str, dict[str, Any]] = {}

    for name, specification in manifest["files"].items():
        if not isinstance(specification, dict):
            raise CopyVerificationError(
                f"Manifest file entry {name!r} must be an object"
            )

        source_label = specification.get("source_path")
        copied_label = specification.get("copied_path")
        if not isinstance(source_label, str) or not isinstance(copied_label, str):
            raise CopyVerificationError(
                f"Manifest file entry {name!r} needs source_path and copied_path"
            )

        observations[name] = _inspect_pair(
            name=name,
            source_label=source_label,
            copied_label=copied_label,
            source_path=_safe_source_path(source_label),
            copied_path=_safe_copied_path(manifest_path, copied_label),
        )

    failed_files = sorted(
        name for name, observation in observations.items() if not observation["passed"]
    )
    report = {
        "status": "failed" if failed_files else "passed",
        "manifest": manifest_path.name,
        "checked_files": len(observations),
        "failed_files": failed_files,
        "files": observations,
    }
    _write_report(report, report_path)

    if failed_files:
        raise CopyVerificationError(
            "Copied files differ from their Phase 1 sources: "
            + ", ".join(failed_files)
        )
    return report


def main() -> None:
    """Run the copy-integrity checker from the command line."""

    # Command-line arguments change file locations only. The comparison rules
    # remain fixed so every independent verification performs the same checks.
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--manifest",
        type=Path,
        default=DEFAULT_MANIFEST_PATH,
        help="Location of the generated tabular dataset manifest.",
    )
    parser.add_argument(
        "--report",
        type=Path,
        default=DEFAULT_REPORT_PATH,
        help="Location for the generated copy-verification report.",
    )
    args = parser.parse_args()

    try:
        report = verify_copied_files(args.manifest, args.report)
    except CopyVerificationError as error:
        print(f"Copy verification failed:\n{error}", file=sys.stderr)
        raise SystemExit(1) from error

    print("Copy verification passed")
    print(f"Files checked: {report['checked_files']}")
    print(f"Report: {args.report.resolve()}")


if __name__ == "__main__":
    main()
